class LanguageManager {
    constructor() {
        this.currentLang = localStorage.getItem('preferredLanguage') || 'uz';
        this.init();
    }

    init() {
        this.setLanguage(this.currentLang);
        this.bindEvents();
    }

    setLanguage(lang) {
        if (!translations[lang]) {
            lang = 'uz';
        }
        
        this.currentLang = lang;
        localStorage.setItem('preferredLanguage', lang);
        
        this.updateTextElements();
        this.updatePlaceholders();
        this.updatePageTitle();
        this.updateSelectElement();
        
        document.dispatchEvent(new CustomEvent('languageChanged', { 
            detail: { language: lang } 
        }));
    }

    updateTextElements() {
        document.querySelectorAll('[data-i18n]').forEach(element => {
            const key = element.getAttribute('data-i18n');
            if (translations[this.currentLang] && translations[this.currentLang][key]) {
                element.innerHTML = translations[this.currentLang][key];
            }
        });
    }

    updatePlaceholders() {
        document.querySelectorAll('[data-i18n-placeholder]').forEach(element => {
            const key = element.getAttribute('data-i18n-placeholder');
            if (translations[this.currentLang] && translations[this.currentLang][key]) {
                element.placeholder = translations[this.currentLang][key];
            }
        });
    }

    updatePageTitle() {
        const titles = {
            uz: 'Old Khiva | Travel',
            ru: 'Old Khiva | Транспорт',
            en: 'Old Khiva | Travel',
            tr: 'Old Khiva | Seyahat',
            de: 'Old Khiva | Reisen'
        };
        
        if (titles[this.currentLang]) {
            document.title = titles[this.currentLang];
        }
    }

    updateSelectElement() {
        const langSelect = document.getElementById('lang');
        if (langSelect) {
            langSelect.value = this.currentLang;
        }
    }

    bindEvents() {
        const langSelect = document.getElementById('lang');
        if (langSelect) {
            langSelect.addEventListener('change', (e) => {
                this.setLanguage(e.target.value);
            });
        }
    }
}

